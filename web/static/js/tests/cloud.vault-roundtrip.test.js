// C2e Task 5 — cross-runtime round-trip contract for the cloud full-vault
// export/import (web/domain/vault.js). The shared golden fixture
// tests/fixtures/vault-v1.json is the same file the Go exporter/importer pin
// (Tasks 2/3): importing it into the cloud record set and re-exporting must be
// identity on `data`, and the intermediate records must carry the deterministic
// recordIds + day-batching the live cloud modules mint (so imported data
// converges by LWW with live devices instead of duplicating).
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  recordsToVault, vaultToRecords, VAULT_MANAGED_TYPES, managedTypesForImport,
} from '../../../../web/domain/vault.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../../../..');
const fixture = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'tests/fixtures/vault-v1.json'), 'utf8'));
// vault-v1-botexport.json is the real Go exporter's output for the same data
// (generated by TestGenerateBotExportFixture): DESC list ordering, no
// cloud-only med_reminder_pref. It pins the cross-runtime contract — a real bot
// file must survive the cloud transforms and canonicalize back to the fixture.
const botExport = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'tests/fixtures/vault-v1-botexport.json'), 'utf8'));

// Fixed clock so id minting is deterministic across runs.
const NOW = Date.parse('2026-07-08T12:00:00Z');

// gps is dropped at import (med-9z3.7): 44% of a real vault, no reader. Identity
// therefore holds on everything BUT gps, so the expectation drops it too.
const dropGps = (data) => {
  const d = JSON.parse(JSON.stringify(data));
  for (const w of d.workouts?.miband || []) delete w.gps;
  return d;
};

describe('cloud vault round-trip (web/domain/vault.js)', () => {
  it('fixture -> vaultToRecords -> recordsToVault is identity on data (minus dropped gps)', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const back = recordsToVault(records, { now: NOW });
    expect(back.format).toBe('medtracker-vault');
    expect(back.version).toBe(1);
    expect(back.data).toEqual(dropGps(fixture.data));
  });

  it('re-attaches goal milestones to the re-minted goal with their goal_set_at (med-8tur.5)', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const goal = records.find((r) => r.recordType === 'weightgoal' && r.set_at === '2026-06-01T09:00:00Z');
    const ms = records.filter((r) => r.recordType === 'gamificationmilestone');
    expect(ms.map((m) => m.recordId)).toEqual([1, 2].map((k) => `gamificationmilestone-${goal.recordId}-${k}`));
    expect(ms.every((m) => m.episode_id === goal.recordId)).toBe(true);
    expect(ms.map((m) => m.acknowledged)).toEqual([true, false]);
    // A pre-milestone file (no key) imports none and re-exports without the key.
    const legacy = JSON.parse(JSON.stringify(fixture));
    delete legacy.data.gamification.milestones;
    const back = recordsToVault(vaultToRecords(legacy, { now: NOW }), { now: NOW });
    expect('milestones' in back.data.gamification).toBe(false);
  });

  it('weekly plans survive export/import: id rebuilt from the week, episode re-attached (med-8tur.4)', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const goal = records.find((r) => r.recordType === 'weightgoal' && r.set_at === '2026-06-01T09:00:00Z');
    const weeks = records.filter((r) => r.recordType === 'gamificationweek');
    expect(weeks.map((w) => w.recordId)).toEqual(['gamificationweek-2026-W27', 'gamificationweek-2026-W28']);
    expect(weeks.every((w) => w.episode_id === goal.recordId)).toBe(true);
    expect(weeks.map((w) => w.paused)).toEqual([false, true]);
    expect(weeks[0].cadence).toEqual({ weigh_in: 'daily', bp_days: 3 });
    // A pre-plan file (no key) imports none and re-exports without the key.
    const legacy = JSON.parse(JSON.stringify(fixture));
    delete legacy.data.gamification.weeks;
    const back = recordsToVault(vaultToRecords(legacy, { now: NOW }), { now: NOW });
    expect('weeks' in back.data.gamification).toBe(false);
  });

  it('drops gps at import and keeps every other miband field', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const miband = records.filter((r) => r.recordType === 'miband');
    expect(miband.length).toBe(fixture.data.workouts.miband.length);
    for (const r of miband) expect('gps' in r).toBe(false);
    const [src] = fixture.data.workouts.miband;
    const { gps, ...expected } = src;
    expect(gps.length).toBeGreaterThan(0); // fixture really does carry a track
    expect(miband[0]).toMatchObject(expected);
  });

  it('canonicalizes a real bot export (Go output) back to the fixture (cross-runtime full loop)', () => {
    // The bot exporter emits DESC-ordered lists and no med_reminder_pref (a
    // cloud-only singleton). recordsToVault sorts every array, so ordering is
    // absorbed; med_reminder_pref and the date-only columns are the documented
    // normalizations (same two the Go TestVaultImportRoundTrip applies).
    const back = recordsToVault(vaultToRecords(botExport, { now: NOW }), { now: NOW });
    const strip = (data) => {
      const d = dropGps(data);
      delete d.settings.med_reminder_pref;
      // Tombstones are a cloud-only v1 addition (med-jtaj); a real bot export
      // never carries them, so they canonicalize away like med_reminder_pref.
      delete d.tombstones;
      // Goal milestones are cloud-only too (med-8tur.5).
      if (d.gamification) delete d.gamification.milestones;
      // So are weekly plans (med-8tur.4).
      if (d.gamification) delete d.gamification.weeks;
      // Equipment is cloud-only inventory (med-niix.1); a real bot export
      // never carries it, so it canonicalizes away here like med_reminder_pref.
      if (d.workouts) delete d.workouts.equipment;
      // Gyms are cloud-only too (med-8j5w.1): the locations list, the
      // active-gym singleton and the per-session stamp.
      if (d.workouts) {
        delete d.workouts.locations;
        delete d.workouts.active_location_id;
        for (const s of d.workouts.sessions || []) { delete s.location_id; delete s.location_name; }
      }
      // equipment_id is the cloud-only binding (med-niix.5 library-level,
      // med-3gln plan-row override); the bot has no such columns, so a real
      // bot export drops them per row — mirrors normalizeVault in
      // vault_import_test.go.
      for (const row of d.workouts?.library || []) delete row.equipment_id;
      for (const row of d.workouts?.exercises || []) delete row.equipment_id;
      // scheduled_date / last_session_date are DATE columns: the bot re-emits them
      // as UTC midnight, the hand fixture writes the local-midnight form. Only the
      // calendar day is contractual — mirrors dateOnlyKeys in vault_import_test.go.
      const day = (s) => (typeof s === 'string' ? s.slice(0, 10) : s);
      for (const s of d.workouts.sessions) s.scheduled_date = day(s.scheduled_date);
      for (const r of d.workouts.rotations) r.last_session_date = day(r.last_session_date);
      return d;
    };
    expect(strip(back.data)).toEqual(strip(fixture.data));
  });

  it('mints deterministic recordIds for scheduled slots, sessions, rotations, and singletons', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const idsByType = (type) => records.filter((r) => r.recordType === type).map((r) => r.recordId);

    // Scheduled intake: intake-<medId>-<slotUnixSeconds>.
    const slotUnix = Math.floor(Date.parse('2026-07-07T07:00:00Z') / 1000);
    expect(idsByType('intake')).toContain(`intake-1-${slotUnix}`);
    // Manual intake (scheduled_at == taken_at) gets a manual id, not a slot id.
    expect(idsByType('intake').some((id) => id.startsWith('intake-manual-'))).toBe(true);

    // Scheduled session: session-<groupId>-<localDate>; rotation: rotation-<groupId>.
    expect(idsByType('workoutsession')).toContain('session-10-2026-07-07');
    expect(idsByType('workoutrotation')).toEqual(['rotation-10']);

    // med-1tj: sleep + miband re-mint on the SAME deterministic natural keys the
    // .nxk migration path (vitals.js importSamples) uses — not import-wall-clock
    // mintNum() — so both cloud import paths converge on one record per night/
    // session instead of double-counting (the 35h-sleep bug).
    expect(idsByType('sleep')).toEqual([`sleep-${Date.parse('2026-07-07T22:30:00Z')}`]);
    const [mb] = fixture.data.workouts.miband;
    expect(idsByType('miband')).toEqual([`miband-${mb.source_start_ms}`]);
    // The body `id` is deterministic too (source instant), matching the merge
    // fallback in vitals.js so a re-drain keeps a stable id.
    expect(records.find((r) => r.recordType === 'miband').id).toBe(mb.source_start_ms);

    // Singletons land on their fixed recordIds (so the live domain modules read them).
    for (const [type, id] of [
      ['bpgoal', 'bpgoal'], ['weightunitpref', 'weight-unit'], ['settings', 'settings'],
      ['features', 'features'], ['taborder', 'taborder'], ['foodtargets', 'foodtargets'],
      ['integrations', 'integrations'], ['medreminderpref', 'medreminderpref'],
      ['bpreminderpref', 'bpreminderpref'], ['weightreminderpref', 'weightreminderpref'],
      ['gamification', 'gamification'], ['apitokens', 'apitokens'],
      ['activelocation', 'activelocation'],
    ]) {
      expect(idsByType(type)).toEqual([id]);
    }

    // Two tz plans: the PENDING_APPROVAL one keeps the recordId the live readers
    // look up; the older COMPLETED one becomes passthrough history.
    expect(idsByType('tzplan').sort()).toEqual(['tzplan-current', 'tzplanhistory-1']);
    const current = records.find((r) => r.recordId === 'tzplan-current');
    expect(current.status).toBe('PENDING_APPROVAL');
    // Bot-only plan metadata rides along on the body so it round-trips.
    expect(current.plan_hash).toBe('hash-pending-0002');
    const past = records.find((r) => r.recordId === 'tzplanhistory-1');
    expect([past.status, past.user_action, past.notified_at])
      .toEqual(['COMPLETED', 'APPROVED', '2026-05-02T09:05:00Z']);

    // Reminder prefs carry the bot-only snooze fields verbatim (no cloud reader).
    const bpPref = records.find((r) => r.recordType === 'bpreminderpref');
    expect(bpPref.snoozed_until).toBe('2026-07-08T18:00:00Z');
    expect(bpPref.dont_remind_until).toBe(null);
    expect(bpPref.preferred_reminder_hour).toBe(20);
  });

  // med-8j5w.1: gyms re-mint on location-<id>; FKs (equipment/session
  // location_id, including the fixture's dangling one) ride verbatim.
  it('round-trips locations, the active gym and dangling location FKs', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const ids = records.filter((r) => r.recordType === 'location').map((r) => r.recordId).sort();
    expect(ids).toEqual(['location-60', 'location-61']);
    expect(records.find((r) => r.recordType === 'activelocation').location_id).toBe(61);
    const back = recordsToVault(records, { now: NOW });
    expect(back.data.workouts.equipment.map((e) => e.location_id)).toEqual([60, 99]);
    expect(back.data.workouts.sessions[0]).toMatchObject({ location_id: 60, location_name: 'Home gym' });
  });

  it('a legacy backup without gyms imports with no locations and no active-gym record', () => {
    const v = JSON.parse(JSON.stringify(fixture));
    delete v.data.workouts.locations;
    delete v.data.workouts.active_location_id;
    const records = vaultToRecords(v, { now: NOW });
    expect(records.some((r) => r.recordType === 'location' || r.recordType === 'activelocation')).toBe(false);
    const back = recordsToVault(records, { now: NOW });
    expect(back.data.workouts.locations).toEqual([]);
    expect('active_location_id' in back.data.workouts).toBe(false);
    // Both types are vault-managed, so the replace clears a stale active gym.
    expect(managedTypesForImport(v).has('activelocation')).toBe(true);
    expect(managedTypesForImport(v).has('location')).toBe(true);
  });

  it('maps a NOTIFIED plan to tzplan-current (bot mode treats it as the live plan)', () => {
    const v = JSON.parse(JSON.stringify(fixture));
    v.data.tz.transition_plans[1].status = 'NOTIFIED';
    const records = vaultToRecords(v, { now: NOW });
    const current = records.find((r) => r.recordId === 'tzplan-current');
    expect(current.status).toBe('NOTIFIED');
  });

  it('emits empty secret blocks (not absent) when includeSecrets and the account has none', () => {
    // A destination restore must be able to CLEAR stale keys/tokens; only an
    // absent block means "leave them alone". Same shape the Go exporter emits.
    const records = vaultToRecords(fixture, { now: NOW })
      .filter((r) => r.recordType !== 'integrations' && r.recordType !== 'apitokens');
    const out = recordsToVault(records, { now: NOW });
    expect(out.data.api_tokens).toEqual([]);
    expect(out.data.settings.integrations).toEqual({});
    expect(managedTypesForImport(out).has('integrations')).toBe(true);
    expect(managedTypesForImport(out).has('apitokens')).toBe(true);
  });

  it('omits the secret-bearing blocks when includeSecrets is false, and keeps them unmanaged on import', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const bare = recordsToVault(records, { now: NOW, includeSecrets: false });
    expect(bare.data.api_tokens).toBeUndefined();
    expect('integrations' in bare.data.settings).toBe(false);
    // Everything else survives the toggle.
    expect(bare.data.gamification).toEqual(fixture.data.gamification);
    expect(bare.data.settings.bp_reminder).toEqual(fixture.data.settings.bp_reminder);

    // A secrets-free vault must not wipe the destination's keys/tokens, so those
    // two record types drop out of the managed (= replaced) set. Mirrors the
    // bot's asymmetric importAPITokens / importSettings rule.
    const narrowed = managedTypesForImport(bare);
    expect(narrowed.has('integrations')).toBe(false);
    expect(narrowed.has('apitokens')).toBe(false);
    expect(narrowed.has('gamification')).toBe(true);
    const full = managedTypesForImport(fixture);
    expect(full.has('integrations')).toBe(true);
    expect(full.has('apitokens')).toBe(true);
  });

  it('packs vitals samples into one day-batch record per UTC calendar day', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    const hr = records.filter((r) => r.recordType === 'hrsample');
    // Fixture heart samples span 07-07 (23:50Z) and 07-08 (00:10Z, 09:00Z).
    expect(hr.map((r) => r.recordId).sort()).toEqual(['hrsample-2026-07-07', 'hrsample-2026-07-08']);
    const day8 = hr.find((r) => r.recordId === 'hrsample-2026-07-08');
    expect(day8.samples.map((s) => s.value)).toEqual([56, 72]);
    // Batch body shape is { day, samples:[...] } — what vitals.js readSamples expects.
    expect(day8.day).toBe('2026-07-08');
  });

  // med-9z3.6 — 57% of a real vault is per-minute HR/SpO2/stress the UI can never
  // display: vitals.js renders HOURLY buckets over a 7d/30d window. Beyond 60d
  // (a month of margin on that window) samples are collapsed to one per UTC hour.
  describe('downsamples vitals older than 60d to hourly averages', () => {
    const wrap = (heart, stress = []) => ({
      format: 'medtracker-vault', version: 1, data: { vitals: { heart, stress } },
    });
    const hrOf = (records, day) => records.find((r) => r.recordId === `hrsample-${day}`).samples;
    const sample = (date_time, value) => ({ date_time, tz_offset: 7200, value });

    it('collapses an old hour to one sample at the hour start, value = round(mean)', () => {
      // 2026-01-01 is >60d before NOW (2026-07-08). Three samples in hour 09.
      const records = vaultToRecords(wrap([
        sample('2026-01-01T09:05:00Z', 60),
        sample('2026-01-01T09:35:00Z', 61),
        sample('2026-01-01T09:55:00Z', 62),
        sample('2026-01-01T10:05:00Z', 80),
      ]), { now: NOW });
      expect(hrOf(records, '2026-01-01')).toEqual([
        { date_time: '2026-01-01T09:00:00Z', tz_offset: 7200, value: 61 },
        { date_time: '2026-01-01T10:00:00Z', tz_offset: 7200, value: 80 },
      ]);
    });

    it('leaves samples inside the 60d window at full resolution', () => {
      const recent = new Date(NOW - 3 * 24 * 60 * 60 * 1000).toISOString().slice(0, 11);
      const records = vaultToRecords(wrap([
        sample(`${recent}09:05:00Z`, 60),
        sample(`${recent}09:35:00Z`, 70),
      ]), { now: NOW });
      const day = new Date(NOW - 3 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
      expect(hrOf(records, day).map((s) => s.value)).toEqual([60, 70]);
    });

    it('is a fixed point: re-importing a cloud export does not drift', () => {
      const original = wrap([
        sample('2026-01-01T09:05:00Z', 60),
        sample('2026-01-01T09:35:00Z', 61),
        sample('2026-01-01T09:55:00Z', 62),
      ]);
      const once = recordsToVault(vaultToRecords(original, { now: NOW }), { now: NOW });
      const twice = recordsToVault(vaultToRecords(once, { now: NOW }), { now: NOW });
      expect(twice.data.vitals.heart).toEqual(once.data.vitals.heart);
    });

    it('reproduces the exact hourly buckets vitals.js would have computed from raw samples', () => {
      // The whole justification: bucketVitals floors to the UTC hour and averages,
      // so averaging into UTC hours at import loses nothing the UI could show.
      const raw = [
        sample('2026-01-01T09:05:00Z', 60),
        sample('2026-01-01T09:35:00Z', 61),
        sample('2026-01-01T09:55:00Z', 65),
      ];
      const [only] = hrOf(vaultToRecords(wrap(raw), { now: NOW }), '2026-01-01');
      const rawAvg = Math.trunc(raw.reduce((a, s) => a + s.value, 0) / raw.length);
      expect(only.value).toBe(rawAvg); // 186/3 = 62 exactly
      expect(Date.parse(only.date_time) % (60 * 60 * 1000)).toBe(0);
    });

    it("drops the stress `info` label beyond the cutoff (a text label has no mean)", () => {
      const records = vaultToRecords(wrap([], [
        { date_time: '2026-01-01T09:05:00Z', tz_offset: 7200, value: 30, info: 'relaxed' },
        { date_time: '2026-01-01T09:45:00Z', tz_offset: 7200, value: 40, info: 'normal' },
      ]), { now: NOW });
      const s = records.find((r) => r.recordId === 'stresssample-2026-01-01').samples;
      expect(s).toEqual([{ date_time: '2026-01-01T09:00:00Z', tz_offset: 7200, value: 35 }]);
    });

    it('does not downsample when the caller supplies no clock', () => {
      // nowMs 0 => negative cutoff => everything fresh. A caller that cannot say
      // when "now" is must not silently collapse the history.
      const records = vaultToRecords(wrap([
        sample('2026-01-01T09:05:00Z', 60),
        sample('2026-01-01T09:35:00Z', 61),
      ]));
      expect(hrOf(records, '2026-01-01').map((s) => s.value)).toEqual([60, 61]);
    });
  });

  it('every produced record type is vault-managed (preserving nk/plumbing on import is the shell shim job)', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    for (const r of records) expect(VAULT_MANAGED_TYPES.has(r.recordType)).toBe(true);
  });

  it('rejects a non-vault file BEFORE the destructive replace (mirrors bot-mode validateVault)', () => {
    // importAll wipes the store then re-inserts these records — a foreign/empty/
    // future file must throw here so the wipe never runs (med data-loss guard).
    expect(() => vaultToRecords({}, { now: NOW })).toThrow();
    expect(() => vaultToRecords({ some: 'other app' }, { now: NOW })).toThrow();
    expect(() => vaultToRecords({ format: 'medtracker-vault', version: 2, data: {} }, { now: NOW })).toThrow();
    expect(() => vaultToRecords(null, { now: NOW })).toThrow();
  });

  it('rejects a structurally-valid vault whose rows cannot mint a recordId', () => {
    // replaceAllRecords clears the store before put()ing; an undefined out-of-line
    // key throws mid-transaction, committing the clear and inserting nothing. So a
    // hand-edited/truncated file must be rejected here, before anything destructive.
    const wrap = (data) => ({ format: 'medtracker-vault', version: 1, data });
    expect(() => vaultToRecords(wrap({ medications: { items: [{ name: 'x' }] } }), { now: NOW })).toThrow(/Corrupt backup/);
    expect(() => vaultToRecords(wrap({ medications: { items: 'abc' } }), { now: NOW })).toThrow(/Corrupt backup/);
    // Natural-key streams (med-1tj) would otherwise mint 'miband-undefined' /
    // 'sleep-undefined' — a non-empty string push() accepts — then silently
    // vanish after the wipe. Reject both before the destructive replace.
    expect(() => vaultToRecords(wrap({ workouts: { miband: [{ steps: 100 }] } }), { now: NOW })).toThrow(/Corrupt backup/);
    expect(() => vaultToRecords(wrap({ vitals: { sleep: [{ start_time: 'not-a-date', duration_min: 400 }] } }), { now: NOW })).toThrow(/Corrupt backup/);
    // A parseable start_time (or a `day` fallback) is fine — no false positives.
    expect(() => vaultToRecords(wrap({ vitals: { sleep: [{ start_time: '2026-07-08T23:00:00Z', duration_min: 400 }] } }), { now: NOW })).not.toThrow();
    expect(() => vaultToRecords(wrap({ vitals: { sleep: [{ start_time: 'not-a-date', day: '2026-07-08', duration_min: 400 }] } }), { now: NOW })).not.toThrow();
    expect(() => vaultToRecords(wrap({ workouts: { miband: [{ source_start_ms: 1751000000000, steps: 100 }] } }), { now: NOW })).not.toThrow();
  });

  it('file content can never override the sync meta fields', () => {
    const records = vaultToRecords({
      format: 'medtracker-vault',
      version: 1,
      data: { diary: { notes: [{ content: 'hi', created_at: '2026-07-08T10:00:00Z', deleted: true, recordId: { evil: 1 }, recordType: 'bp' }] } },
    }, { now: NOW });
    const note = records.find((r) => r.recordType === 'note');
    expect(note).toBeTruthy();
    expect(note.deleted).toBe(false);
    expect(typeof note.recordId).toBe('string');
  });

  it('keeps a tz_step intake distinct from its shadowed schedule sibling', () => {
    const slot = '2026-07-10T07:00:00Z';
    const records = vaultToRecords({
      format: 'medtracker-vault',
      version: 1,
      data: {
        medications: {
          intakes: [
            { medication_id: 1, scheduled_at: slot, taken_at: null, status: 'PENDING', source: 'schedule' },
            { medication_id: 1, scheduled_at: slot, taken_at: null, status: 'PENDING', source: 'tz_step', tz_plan_id: 2, tz_step_number: 1 },
          ],
        },
      },
    }, { now: NOW });
    const ids = records.filter((r) => r.recordType === 'intake').map((r) => r.recordId);
    expect(new Set(ids).size).toBe(2);
    expect(ids).toContain(`intake-1-${Math.floor(Date.parse(slot) / 1000)}`);
  });

  it('round-trips derived-slot tombstones: a deleted day stays deleted (med-jtaj)', () => {
    const records = vaultToRecords(fixture, { now: NOW });
    // The intermediate records carry bodyless suppression signals, exactly what
    // records.del writes — no body for any reader to lean on.
    const tombs = records.filter((r) => r.deleted);
    expect(tombs.map((r) => `${r.recordType}:${r.recordId}`).sort()).toEqual([
      'intake:intake-1-1783580400',
      'workoutsession:session-10-2026-07-09',
    ]);
    for (const t of tombs) {
      expect(Object.keys(t).sort()).toEqual(['clientTs', 'deleted', 'recordId', 'recordType']);
    }
    // ... and the re-export reproduces the tombstones block (also pinned by the
    // identity test above; asserted here for the failure message).
    const back = recordsToVault(records, { now: NOW });
    expect(back.data.tombstones).toEqual(fixture.data.tombstones);
  });

  it('exports only derived-slot-shaped tombstones; old files without the key import as today', () => {
    // A deleted note is delete-by-absence: absence already means deleted after
    // a replace-only import, so its tombstone is correctly dropped on export —
    // as are manually-keyed (`intake-manual-…`, `session-adhoc-…`) and suffixed
    // (`intake-<m>-<s>-tz_step`, which nothing looks up) tombstones: only exact
    // derived-slot shapes suppress re-materialization.
    const records = vaultToRecords(fixture, { now: NOW });
    const withExtra = [
      ...records,
      { recordType: 'note', recordId: '999', clientTs: NOW, deleted: true },
      { recordType: 'intake', recordId: 'intake-manual-123-456', clientTs: NOW, deleted: true },
      { recordType: 'intake', recordId: 'intake-1-1783580400-tz_step', clientTs: NOW, deleted: true },
      { recordType: 'workoutsession', recordId: 'session-adhoc-5', clientTs: NOW, deleted: true },
      { recordType: 'workoutsession', recordId: 'session-10-2026-07-11', clientTs: NOW, deleted: true },
    ];
    const out = recordsToVault(withExtra, { now: NOW });
    expect(out.data.tombstones).toEqual([
      { recordType: 'intake', recordId: 'intake-1-1783580400' },
      { recordType: 'workoutsession', recordId: 'session-10-2026-07-09' },
      { recordType: 'workoutsession', recordId: 'session-10-2026-07-11' },
    ]);

    // Old files (no tombstones key) import with zero tombstone records —
    // exactly today's behavior — and export without the key.
    const legacy = JSON.parse(JSON.stringify(fixture));
    delete legacy.data.tombstones;
    const legacyRecords = vaultToRecords(legacy, { now: NOW });
    expect(legacyRecords.some((r) => r.deleted)).toBe(false);
    expect(recordsToVault(legacyRecords, { now: NOW }).data.tombstones).toBeUndefined();
  });

  it('skips unknown tombstone types; rejects bad slot shapes and cross-type collisions (med-jtaj)', () => {
    const bad = (tombstones) => ({ format: 'medtracker-vault', version: 1, data: { tombstones } });
    // Unknown record types are SKIPPED (forward-compat: an older app importing
    // a newer backup must not choke on slot types it doesn't know yet).
    const future = vaultToRecords(bad([
      { recordType: 'note', recordId: '999' },
      { recordType: 'bogus', recordId: 'x' },
    ]), { now: NOW });
    expect(future.some((r) => r.deleted)).toBe(false);

    // A KNOWN slot type with a non-matching id shape: Corrupt backup before
    // the destructive replace — a hand-edited file must not tombstone arbitrary
    // records (e.g. {intake, 'settings'} over the settings singleton).
    for (const t of [
      { recordType: 'intake' },
      { recordType: 'intake', recordId: '' },
      { recordType: 'intake', recordId: 'intake-manual-123-456' },
      { recordType: 'intake', recordId: 'intake-1-1783580400-tz_step' },
      { recordType: 'intake', recordId: 'settings' },
      { recordType: 'workoutsession', recordId: 'session-adhoc-5' },
    ]) {
      expect(() => vaultToRecords(bad([t]), { now: NOW })).toThrow(/Corrupt backup/);
    }

    // Cross-type recordId collision: the store is keyed by recordId alone, so a
    // tombstone sharing its id with another type's live row would overwrite it.
    const clashType = {
      format: 'medtracker-vault',
      version: 1,
      data: {
        medications: { items: [{ id: 'session-10-2026-07-09', name: 'x' }] },
        tombstones: [{ recordType: 'workoutsession', recordId: 'session-10-2026-07-09' }],
      },
    };
    expect(() => vaultToRecords(clashType, { now: NOW })).toThrow(/Corrupt backup/);

    // Same-type collision: the live row wins, a single live record out.
    const clash = JSON.parse(JSON.stringify(fixture));
    clash.data.tombstones.push({ recordType: 'workoutsession', recordId: 'session-10-2026-07-07' });
    const slot = vaultToRecords(clash, { now: NOW })
      .filter((r) => r.recordType === 'workoutsession' && r.recordId === 'session-10-2026-07-07');
    expect(slot).toHaveLength(1);
    expect(slot[0].deleted).toBe(false);
  });
});
