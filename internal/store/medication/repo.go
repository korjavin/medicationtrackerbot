// materializedStep is the minimal projection of tzreschedule.TransitionStep
// that MaterializePlanStepsAsIntakesTx needs in order to insert intake_log
// rows. The JSON keys mirror the PascalCase shape produced by
// `json.Marshal([]tzreschedule.TransitionStep)` in planner.go, so the same
// blob stored in tz_transition_plans.steps_json round-trips cleanly here.
type materializedStep struct {
	MedicationID int64     `json:"MedicationID"`
	StepNumber   int       `json:"StepNumber"`
	ScheduledAt  time.Time `json:"ScheduledAt"`
}

// MaterializePlanStepsAsIntakesTx reads the plan's steps_json blob and
// inserts one PENDING source='tz_step' row into intake_log per step. The
// insert uses INSERT OR IGNORE against the partial unique index added by
// migration 067, so re-running the materialize on the same plan (e.g. after a
// tx commit failure or a benign re-approve) is a no-op rather than a
// duplicate-key error.
//
// Track D Task 13 dropped the tz_transition_steps table; steps_json is now the
// single source of truth for "what doses does this plan introduce". The
// planner already serializes []tzreschedule.TransitionStep into that column at
// plan-create time, so this method does not need to touch any other table.
//
// Returns the number of rows actually inserted (zero on a re-run). Caller is
// responsible for the surrounding transaction (typically Repos.ApproveAndMaterialize).
func (r *Repo) MaterializePlanStepsAsIntakesTx(tx storedb.TX, planID, allowedUserID int64) (int64, error) {
	var stepsJSON string
	if err := tx.QueryRow(`SELECT steps_json FROM tz_transition_plans WHERE id = ?`, planID).Scan(&stepsJSON); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return 0, nil
		}
		return 0, fmt.Errorf("materialize plan %d: load steps_json: %w", planID, err)
	}
	if stepsJSON == "" {
		return 0, nil
	}
	var steps []materializedStep
	if err := json.Unmarshal([]byte(stepsJSON), &steps); err != nil {
		return 0, fmt.Errorf("materialize plan %d: parse steps_json: %w", planID, err)
	}
	if len(steps) == 0 {
		return 0, nil
	}
	var total int64
	for _, s := range steps {
		if s.MedicationID == 0 || s.StepNumber == 0 {
			continue
		}
		res, err := tx.Exec(`
			INSERT OR IGNORE INTO intake_log
			  (medication_id, user_id, scheduled_at_unix, status,
			   source, tz_plan_id, tz_step_number)
			VALUES (?, ?, ?, 'PENDING', 'tz_step', ?, ?)`,
			s.MedicationID, allowedUserID, s.ScheduledAt.UTC().Unix(), planID, s.StepNumber)
		if err != nil {
			return total, fmt.Errorf("materialize plan %d step %d: %w", planID, s.StepNumber, err)
		}
		n, _ := res.RowsAffected()
		total += n
	}
	return total, nil
}

// DeletePendingPreMaterializedIntakesForPlan removes every PENDING intake_log
// row that was pre-materialized for the given plan (source='tz_step',
// tz_plan_id=planID). Rows the user has already confirmed (status='TAKEN')
// belong to the user even after a plan cancel, so they survive.
//
// Used by the planner's cancel path: when a plan is cancelled (superseded by a
// new tz change, rejected via the banner, etc.) the unfired step rows must be
// removed so the medication scheduler does not keep firing them.
func (r *Repo) DeletePendingPreMaterializedIntakesForPlan(planID int64) error {
	_, err := r.db.Exec(`
		DELETE FROM intake_log
		WHERE tz_plan_id = ? AND status = 'PENDING' AND source = 'tz_step'`, planID)
	return err
}

// GetDueTZStepIntakes returns every PENDING intake_log row with
// source='tz_step' whose scheduled_at_unix is at-or-before asOf and which
// has not yet been notified (no intake_reminders row references it). Used
// by MedicationChecker.Check to surface pre-materialized transition-plan
// step rows as fire-targets — see Task 11 of the scheduling-simplification
// plan (docs/plans/20260508-simplify-medication-scheduling-utc-and-pre-materialized-steps.md).
//
// The intake_reminders gate is what stops the medication scheduler from
// re-firing the same tz_step row on every 1-minute tick. Normal-schedule
// rows are deduped via "row already exists in intake_log" (BatchGet skips
// them after the first fire); tz_step rows already exist at approve time,
// so they need a separate gate. After the first fire AddIntakeReminder
// writes an intake_reminders row; subsequent ticks skip the intake here and
// MedicationReminderChecker takes over re-reminders via its snooze loop.
//
// Defense in depth: this also requires the owning tz_transition_plan to be
// in APPROVED or COMPLETED status. The plan-cancel path
// (DeletePendingPreMaterializedIntakesForPlan) is best-effort — if its
// DELETE fails after the plan-status UPDATE succeeds, leftover tz_step rows
// would otherwise fire here even though the plan was cancelled. The plan
// join makes that impossible by construction. COMPLETED is included because
// the scheduler may flip an APPROVED plan to COMPLETED earlier in the same
// tick (when no future PENDING steps remain) and we still want any
// past-but-unfired step rows to fire on this tick.
func (r *Repo) GetDueTZStepIntakes(asOf time.Time) ([]IntakeLog, error) {
	rows, err := r.db.Query(`
		SELECT id, medication_id, user_id, scheduled_at_unix, status, snoozed_until_unix,
		       source, tz_plan_id, tz_step_number
		FROM intake_log
		WHERE status = 'PENDING' AND source = 'tz_step'
		  AND scheduled_at_unix <= ?
		  AND tz_plan_id IS NOT NULL
		  AND EXISTS (
		    SELECT 1 FROM tz_transition_plans p
		    WHERE p.id = intake_log.tz_plan_id
		      AND p.status IN ('APPROVED', 'COMPLETED')
		  )
		  AND NOT EXISTS (
		    SELECT 1 FROM intake_reminders r WHERE r.intake_id = intake_log.id
		  )`, asOf.UTC().Unix())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var logs []IntakeLog
	for rows.Next() {
		var l IntakeLog
		var schedUnix int64
		var snoozeUnix sql.NullInt64
		var tzPlanID, tzStepNumber sql.NullInt64
		if err := rows.Scan(&l.ID, &l.MedicationID, &l.UserID, &schedUnix, &l.Status, &snoozeUnix, &l.Source, &tzPlanID, &tzStepNumber); err != nil {
			return nil, err
		}
		l.ScheduledAt = time.Unix(schedUnix, 0).UTC()
		if snoozeUnix.Valid {
			t := time.Unix(snoozeUnix.Int64, 0).UTC()
			l.SnoozedUntil = &t
		}
		if tzPlanID.Valid {
			v := tzPlanID.Int64
			l.TZPlanID = &v
		}
		if tzStepNumber.Valid {
			v := tzStepNumber.Int64
			l.TZStepNumber = &v
		}
		logs = append(logs, l)
	}
	return logs, rows.Err()
}

// CountFuturePendingTZStepIntakesForPlan returns the number of PENDING
// intake_log rows for the given plan whose scheduled_at_unix is strictly
// after asOf. The medication scheduler uses this to mark an APPROVED plan
// COMPLETED once all of its pre-materialized step times have arrived (the
// pre-Track-D equivalent was "no remaining unconsumed tz_transition_steps").
func (r *Repo) CountFuturePendingTZStepIntakesForPlan(planID int64, asOf time.Time) (int, error) {
	var n int
	err := r.db.QueryRow(`
		SELECT COUNT(*) FROM intake_log
		WHERE tz_plan_id = ? AND source = 'tz_step'
		  AND status = 'PENDING'
		  AND scheduled_at_unix > ?`, planID, asOf.UTC().Unix()).Scan(&n)
	return n, err
}

// MedsWithFuturePendingTZStepsForPlan returns the distinct medication IDs
// that still have at least one PENDING source='tz_step' row in intake_log
// with scheduled_at_unix > asOf for the given plan. The medication scheduler
// uses this to skip normal-schedule emission for those meds while an
// APPROVED plan still has steps to fire, restoring the pre-Track-D
// "plan owns this med while steps remain" suppression. Without it the
// symmetric ±minInterval dedup (HasIntakeNearScheduledTime) only covers
// targets within minInterval of an existing step row; a normal slot that
// falls in a gap > 2*minInterval between consecutive steps would otherwise
// fire mid-transition.
func (r *Repo) MedsWithFuturePendingTZStepsForPlan(planID int64, asOf time.Time) ([]int64, error) {
	rows, err := r.db.Query(`
		SELECT DISTINCT medication_id FROM intake_log
		WHERE tz_plan_id = ? AND source = 'tz_step'
		  AND status = 'PENDING'
		  AND scheduled_at_unix > ?`, planID, asOf.UTC().Unix())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []int64
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err != nil {
			return nil, err
		}
		out = append(out, id)
	}
	return out, rows.Err()
}

// HasIntakeNearScheduledTime reports whether an intake_log row for the given
// medication exists within ±window of target, with status in
// ('PENDING', 'TAKEN'). The scheduler uses this as the symmetric
// ±minInterval dedup replacement for medplan's removed consumed-step
// overlap guard — see Task 11 of the scheduling-simplification plan.
func (r *Repo) HasIntakeNearScheduledTime(medID int64, target time.Time, window time.Duration) (bool, error) {
	if window < 0 {
		window = -window
	}
	targetUnix := target.UTC().Unix()
	windowSec := int64(window / time.Second)
	var n int
	err := r.db.QueryRow(`
		SELECT COUNT(*) FROM intake_log
		WHERE medication_id = ?
		  AND status IN ('PENDING', 'TAKEN')
		  AND scheduled_at_unix BETWEEN ? AND ?
		  AND `+tzStepPlanStatusGateForDedup+`
		LIMIT 1`, medID, targetUnix-windowSec, targetUnix+windowSec).Scan(&n)
	if err != nil {
		return false, err
	}
	return n > 0, nil
}

// GetPendingIntakesInWindow returns every PENDING intake_log row whose
// scheduled_at_unix lies in (start, end]. Used by the next-intake forecast
// endpoints to surface pre-materialized tz_step rows (and any other PENDING
// rows) alongside medplan's normal-schedule targets — see Task 12 of
// docs/plans/20260508-simplify-medication-scheduling-utc-and-pre-materialized-steps.md.
// The window matches medplan's forecast-mode predicate so the two sources
// dedup cleanly on (medication_id, scheduled_at_unix).
//
// Defense in depth: source='tz_step' rows are only returned when their owning
// tz_transition_plan is in APPROVED or COMPLETED status — mirroring the gate
// in GetDueTZStepIntakes. The plan-cancel path
// (DeletePendingPreMaterializedIntakesForPlan) is best-effort, so a leftover
// PENDING tz_step row could otherwise appear in the forecast / Take-next
// surfaces (via suppressNormalsCoveredByStep it would also hide the normal
// target for that med) even after the user dismissed the plan. Non-tz_step
// rows (source='schedule' and any future sources) bypass this gate and are
// always returned when PENDING.
//
// Rows are ordered so that source='tz_step' rows appear first at any
// (medication_id, scheduled_at_unix). The forecast/Take-next dedup
// (medication_handlers.go / settings_handlers.go) keeps the first row it sees
// at each key, then suppressNormalsCoveredByStep drops any remaining
// SourceNormalSchedule entry for plan-owned meds. Without the ordering a
// pre-existing source='schedule' row at the same instant as a materialized
// step would win the dedup, get marked SourceNormalSchedule, and then be
// dropped by the plan-owned suppression — silently hiding the dose. The
// schedule row can co-exist if the normal scheduler fired at T just before
// the user approved a plan whose snap-to-clock final step also landed at T.
func (r *Repo) GetPendingIntakesInWindow(start, end time.Time) ([]IntakeLog, error) {
	rows, err := r.db.Query(`
		SELECT id, medication_id, user_id, scheduled_at_unix, status, snoozed_until_unix,
		       source, tz_plan_id, tz_step_number
		FROM intake_log
		WHERE status = 'PENDING'
		  AND scheduled_at_unix > ? AND scheduled_at_unix <= ?
		  AND `+tzStepPlanStatusGate+`
		ORDER BY scheduled_at_unix, medication_id,
		         CASE WHEN source = 'tz_step' THEN 0 ELSE 1 END,
		         id`,
		start.UTC().Unix(), end.UTC().Unix())
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var logs []IntakeLog
	for rows.Next() {
		var l IntakeLog
		var schedUnix int64
		var snoozeUnix sql.NullInt64
		var tzPlanID, tzStepNumber sql.NullInt64
		if err := rows.Scan(&l.ID, &l.MedicationID, &l.UserID, &schedUnix, &l.Status, &snoozeUnix, &l.Source, &tzPlanID, &tzStepNumber); err != nil {
			return nil, err
		}
		l.ScheduledAt = time.Unix(schedUnix, 0).UTC()
		if snoozeUnix.Valid {
			t := time.Unix(snoozeUnix.Int64, 0).UTC()
			l.SnoozedUntil = &t
		}
		if tzPlanID.Valid {
			v := tzPlanID.Int64
			l.TZPlanID = &v
		}
		if tzStepNumber.Valid {
			v := tzStepNumber.Int64
			l.TZStepNumber = &v
		}
		logs = append(logs, l)
	}
	return logs, rows.Err()
}
