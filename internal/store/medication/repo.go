// GetIntakeBySchedule returns the intake_log row at (medID, scheduledAt) that
// is logically active. Orphan PENDING source='tz_step' rows whose owning plan
// is not APPROVED/COMPLETED are hidden via tzStepPlanStatusGateForDedup so
// callers that act on the result (Take-next, confirm-schedule, /next) don't
// pick up a zombie row that ConfirmIntake will then reject — when an orphan
// shares (medication_id, scheduled_at_unix) with a legitimate normal target
// the handler would otherwise see the orphan, fail to confirm it, and skip
// the slot entirely. TAKEN tz_step rows from any plan, and PENDING tz_step
// rows from APPROVED/COMPLETED plans, still pass through. Tests that need
// to introspect physical persistence of an orphan row must query intake_log
// directly.
//
// When a (medID, scheduledAt) slot has BOTH a source='schedule' row and a
// source='tz_step' row (e.g. the normal scheduler fired at T just before the
// user approved a plan whose final snap-to-clock step also landed at T), the
// tz_step row wins via the ORDER BY tiebreaker. Confirming the schedule row
// instead would leave the pre-materialized step PENDING — visible to the
// scheduler's fire path on the next tick — so prefer the plan-owned row.
func (r *Repo) GetIntakeBySchedule(medID int64, scheduledAt time.Time) (*IntakeLog, error) {
	var l IntakeLog
	var schedUnix int64
	var takenUnix sql.NullInt64
	var snoozeUnix sql.NullInt64
	var tzPlanID, tzStepNumber sql.NullInt64
	err := r.db.QueryRow(`SELECT id, medication_id, user_id, scheduled_at_unix, taken_at_unix, status, snoozed_until_unix, source, tz_plan_id, tz_step_number
		FROM intake_log
		WHERE medication_id = ? AND scheduled_at_unix = ?
		  AND `+tzStepPlanStatusGateForDedup+`
		ORDER BY CASE WHEN source = 'tz_step' THEN 0 ELSE 1 END, id
		LIMIT 1`, medID, scheduledAt.UTC().Unix()).Scan(
		&l.ID, &l.MedicationID, &l.UserID, &schedUnix, &takenUnix, &l.Status, &snoozeUnix, &l.Source, &tzPlanID, &tzStepNumber,
	)
	if err == sql.ErrNoRows {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	l.ScheduledAt = time.Unix(schedUnix, 0).UTC()
	if takenUnix.Valid {
		t := time.Unix(takenUnix.Int64, 0).UTC()
		l.TakenAt = &t
	}
	if snoozeUnix.Valid {
		t := time.Unix(snoozeUnix.Int64, 0).UTC()
		l.SnoozedUntil = &t
	}
	if tzPlanID.Valid {
		v := tzPlanID.Int64
		l.TZPlanID = &v
	}
	if tzStepNumber.Valid {
		v := tzStepNumber.Int64
		l.TZStepNumber = &v
	}
	return &l, nil
}

func (r *Repo) BatchGetIntakesBySchedule(schedules []MedicationSchedule) (map[MedicationSchedule]*IntakeLog, error) {
	result := make(map[MedicationSchedule]*IntakeLog, len(schedules))
	if len(schedules) == 0 {
		return result, nil
	}

	// SQLite maximum variables is typically 32766, but we'll use a conservative batch size.
	// Each tuple (medication_id, scheduled_at_unix) uses 2 variables.
	// 500 schedules * 2 = 1000 variables per batch.
	const batchSize = 500

	for i := 0; i < len(schedules); i += batchSize {
		end := i + batchSize
		if end > len(schedules) {
			end = len(schedules)
		}

		batch := schedules[i:end]
		placeholders := make([]string, len(batch))
		args := make([]interface{}, len(batch)*2)

		for j, sched := range batch {
			placeholders[j] = "(?, ?)"
			args[j*2] = sched.MedID
			args[j*2+1] = sched.ScheduledAt.UTC().Unix()
		}

		query := fmt.Sprintf(
			"SELECT id, medication_id, user_id, scheduled_at_unix, taken_at_unix, status, snoozed_until_unix, source, tz_plan_id, tz_step_number FROM intake_log WHERE (medication_id, scheduled_at_unix) IN (%s) AND %s",
			strings.Join(placeholders, ", "),
			tzStepPlanStatusGateForDedup,
		)

		rows, err := r.db.Query(query, args...)
		if err != nil {
			return nil, err
		}

		for rows.Next() {
			var l IntakeLog
			var schedUnix int64
			var takenUnix sql.NullInt64
			var snoozeUnix sql.NullInt64
			var tzPlanID, tzStepNumber sql.NullInt64
			err := rows.Scan(
				&l.ID, &l.MedicationID, &l.UserID, &schedUnix, &takenUnix, &l.Status, &snoozeUnix, &l.Source, &tzPlanID, &tzStepNumber,
			)
			if err != nil {
				rows.Close()
				return nil, err
			}
			l.ScheduledAt = time.Unix(schedUnix, 0).UTC()
			if takenUnix.Valid {
				t := time.Unix(takenUnix.Int64, 0).UTC()
				l.TakenAt = &t
			}
			if snoozeUnix.Valid {
				t := time.Unix(snoozeUnix.Int64, 0).UTC()
				l.SnoozedUntil = &t
			}
			if tzPlanID.Valid {
				v := tzPlanID.Int64
				l.TZPlanID = &v
			}
			if tzStepNumber.Valid {
				v := tzStepNumber.Int64
				l.TZStepNumber = &v
			}
			// Key by UTC. Callers that look up with a non-UTC ScheduledAt
			// must convert via .UTC() — the scheduler dedupe path already does so.
			result[MedicationSchedule{MedID: l.MedicationID, ScheduledAt: l.ScheduledAt}] = &l
		}
		if err := rows.Err(); err != nil {
			return nil, err
		}
		rows.Close()
	}

	return result, nil
}

// ConfirmIntakesBySchedule marks every PENDING intake whose scheduled_at_unix
// matches the supplied target as TAKEN, returning the IDs that were updated.
// The comparison is on the INTEGER scheduled_at_unix column, so it is
// independent of the caller's time.Location.
func (r *Repo) ConfirmIntakesBySchedule(userID int64, scheduledAt time.Time, takenAt time.Time) ([]int64, error) {
	candidates, err := r.ListPendingIntakesBySchedule(userID, scheduledAt)
	if err != nil {
		return nil, err
	}

	var ids []int64
	for _, c := range candidates {
		// ConfirmIntake guards on status='PENDING', so a concurrent confirm
		// returns sql.ErrNoRows here — treat that as "already taken" and skip
		// instead of failing the batch.
		if err := r.ConfirmIntake(c.ID, takenAt); err != nil {
			if errors.Is(err, sql.ErrNoRows) {
				continue
			}
			return nil, err
		}
		ids = append(ids, c.ID)
	}
	return ids, nil
}

